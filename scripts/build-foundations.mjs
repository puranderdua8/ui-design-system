// Writes packages/ui/dist/foundations.css (hand-written theme.css: Tailwind
// bridge + recipes, no token values, D-056) and copies the generated theme
// files to dist/themes/. No `@import "tailwindcss"` inside: consumers import
// Tailwind themselves (D-005).
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const styles = resolve(root, "packages/ui/src/styles");
const out = resolve(root, "packages/ui/dist/foundations.css");

const theme = readFileSync(resolve(styles, "theme.css"), "utf8");

const css = `/* @puranderdua/ui foundations: Tailwind v4 bridge + recipes, no token values. Import one themes/<name>.css as well. Generated by scripts/build-foundations.mjs. */\n\n${theme.trim()}\n`;

if (/@import\s+["']tailwindcss/.test(css)) {
  console.error('foundations.css must not contain @import "tailwindcss".');
  process.exit(1);
}

// Class lists for `cn()` (tailwind-merge) derived from theme.css, so the
// bridge stays the single source and the lists cannot drift.
const sizes = [...theme.matchAll(/--text-ds-([a-z0-9]+(?:-[a-z0-9]+)?):/g)]
  .map((m) => `ds-${m[1]}`)
  .filter((v, i, a) => a.indexOf(v) === i);
const recipes = [...theme.matchAll(/^\s*\.(ds-type-[a-z0-9-]+)\s*\{/gm)].map(
  (m) => m[1],
);
if (!sizes.length || !recipes.length) {
  console.error("theme.css: no --text-ds-* sizes or .ds-type-* recipes found.");
  process.exit(1);
}
// Bridge namespaces that tailwind-merge sorts by value shape (T-shirt sizes,
// numbers). Without these, `shadow-ds-raised` reads as a shadow colour,
// `max-w-ds-md` and `rounded-ds-card` go ungrouped, and a later `shadow-md`
// would not replace them. Keys are tailwind-merge theme keys.
const THEME_NAMESPACES = {
  shadow: "shadow",
  radius: "radius",
  container: "container",
  spacing: "spacing",
  ease: "ease",
};
const themeValues = Object.fromEntries(
  Object.entries(THEME_NAMESPACES).map(([key, ns]) => [
    key,
    [...theme.matchAll(new RegExp(`--${ns}-(ds-[a-z0-9-]+):`, "g"))].map(
      (m) => m[1],
    ),
  ]),
);
for (const [key, values] of Object.entries(themeValues))
  if (!values.length) {
    console.error(
      `theme.css: no --${THEME_NAMESPACES[key]}-ds-* entries found.`,
    );
    process.exit(1);
  }
const list = (xs) => `[${xs.map((x) => JSON.stringify(x)).join(", ")}]`;
const classesFile = resolve(
  root,
  "packages/ui/src/lib/generated/ds-classes.ts",
);
mkdirSync(dirname(classesFile), { recursive: true });
writeFileSync(
  classesFile,
  `// GENERATED by scripts/build-foundations.mjs from styles/theme.css. Do not edit.
/** Values for the \`text-<size>\` utilities (font-size namespace). */
export const dsFontSizes: string[] = ${list(sizes)};
/** \`.ds-type-<role>\` recipe classes (each sets family, size, weight, leading, tracking). */
export const dsTypeRecipes: string[] = ${list(recipes)};
/** Values per tailwind-merge theme key (shadow, radius, container, spacing, ease). */
export const dsThemeValues: Record<string, string[]> = {
${Object.entries(themeValues)
  .map(([key, values]) => `  ${key}: ${list(values)},`)
  .join("\n")}
};
`,
);

const themesSrc = resolve(styles, "generated/themes");
if (!existsSync(themesSrc)) {
  console.error("No generated themes; run pnpm tokens:build first.");
  process.exit(1);
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
cpSync(themesSrc, resolve(dirname(out), "themes"), { recursive: true });
console.log(`foundations.css written (${css.length} bytes)`);

// Concatenates generated tokens.css + hand-written theme.css into
// packages/ui/dist/foundations.css. No `@import "tailwindcss"` inside:
// consumers import Tailwind themselves (D-005).
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const styles = resolve(root, "packages/ui/src/styles");
const out = resolve(root, "packages/ui/dist/foundations.css");

const tokens = readFileSync(resolve(styles, "generated/tokens.css"), "utf8");
const theme = readFileSync(resolve(styles, "theme.css"), "utf8");

const css = `/* @puranderdua/ui foundations: tokens + Tailwind v4 bridge + recipes. Generated by scripts/build-foundations.mjs. */\n\n${tokens.trim()}\n\n${theme.trim()}\n`;

if (/@import\s+["']tailwindcss/.test(css)) {
  console.error('foundations.css must not contain @import "tailwindcss".');
  process.exit(1);
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
console.log(`foundations.css written (${css.length} bytes)`);

// Writes packages/ui/dist/foundations.css (hand-written theme.css: Tailwind
// bridge + recipes, no token values, D-056) and copies the generated theme
// files to dist/themes/ and contrast-pairs.json to dist/. No `@import "tailwindcss"` inside: consumers import
// Tailwind themselves (D-005). Runs after tsup, which cleans dist.
// (The `cn()` class lists come from scripts/build-classes.mjs, before tsup.)
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const styles = resolve(root, "packages/ui/src/styles");
const out = resolve(root, "packages/ui/dist/foundations.css");

const theme = readFileSync(resolve(styles, "theme.css"), "utf8");

// The shared stacking scale (--ds-layer-*) is not themeable, so it ships here
// and not in themes/<name>.css (D-075).
const layersFile = resolve(styles, "generated/layers.css");
if (!existsSync(layersFile)) {
  console.error("No generated layers.css; run pnpm tokens:build first.");
  process.exit(1);
}
const layers = readFileSync(layersFile, "utf8").replace(
  /^\/\*[\s\S]*?\*\/\s*/,
  "",
);

const css = `/* @puranderdua/ui foundations: Tailwind v4 bridge + recipes, plus the shared layer scale. No themeable token values. Import one themes/<name>.css as well. Generated by scripts/build-foundations.mjs. */\n\n${layers.trim()}\n\n${theme.trim()}\n`;

if (/@import\s+["']tailwindcss/.test(css)) {
  console.error('foundations.css must not contain @import "tailwindcss".');
  process.exit(1);
}

const themesSrc = resolve(styles, "generated/themes");
if (!existsSync(themesSrc)) {
  console.error("No generated themes; run pnpm tokens:build first.");
  process.exit(1);
}
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, css);
cpSync(themesSrc, resolve(dirname(out), "themes"), { recursive: true });
// Ships the WCAG pairs the playground checks live (D-052, D-060).
cpSync(
  resolve(root, "tokens/contrast-pairs.json"),
  resolve(dirname(out), "contrast-pairs.json"),
);
console.log(`foundations.css written (${css.length} bytes)`);
